package com.kq.acdos.data.remote

import com.squareup.moshi.Json
import com.squareup.moshi.JsonClass
import java.time.Instant
import retrofit2.Response
import retrofit2.http.Body
import retrofit2.http.GET
import retrofit2.http.Header
import retrofit2.http.POST
import retrofit2.http.Path

/**
 * The dispatcher's optimisation runs (#51). Only the dispatcher screens (#27)
 * call this. The routes will require a dispatcher token: anyone else gets 403,
 * which never triggers a token refresh and reaches the caller through
 * [apiCall] as ErrorCode.FORBIDDEN ("not allowed").
 */
interface OptimisationJobsApi {
    /**
     * 202 with the job id. [idempotencyKey] is generated by the caller and
     * reused on a retry, so a retried POST returns the same job.
     */
    @POST("optimisation-jobs")
    suspend fun createJob(
        @Header("Idempotency-Key") idempotencyKey: String,
        @Body body: OptimisationJobCreateDto
    ): Response<OptimisationJobAcceptedDto>

    @GET("optimisation-jobs/{job_id}")
    suspend fun getJob(@Path("job_id") jobId: String): Response<OptimisationJobResultDto>
}

// DTOs match docs/openapi.json (OpenApiContractTest checks it). Ids stay strings.

enum class OptimizationTriggerTypeDto {
    @Json(name = "scheduled")
    SCHEDULED,

    @Json(name = "flight_delay")
    FLIGHT_DELAY,

    @Json(name = "standby_activation")
    STANDBY_ACTIVATION,

    @Json(name = "vehicle_breakdown")
    VEHICLE_BREAKDOWN
}

enum class OptimizationJobStatusDto {
    @Json(name = "queued")
    QUEUED,

    @Json(name = "running")
    RUNNING,

    @Json(name = "completed")
    COMPLETED,

    @Json(name = "failed")
    FAILED
}

@JsonClass(generateAdapter = true)
data class OptimisationJobCreateDto(
    @Json(name = "trigger_type") val triggerType: OptimizationTriggerTypeDto,
    @Json(name = "pickup_request_ids") val pickupRequestIds: List<String>,
    @Json(name = "vehicle_ids") val vehicleIds: List<String>
)

@JsonClass(generateAdapter = true)
data class OptimisationJobAcceptedDto(val id: String)

@JsonClass(generateAdapter = true)
data class PlannedNodeDto(
    @Json(name = "pickup_request_id") val pickupRequestId: String,
    @Json(name = "seq_order") val seqOrder: Int,
    @Json(name = "estimated_arrival") val estimatedArrival: Instant
)

@JsonClass(generateAdapter = true)
data class PlannedRouteDto(
    @Json(name = "vehicle_id") val vehicleId: String,
    @Json(name = "total_distance_km") val totalDistanceKm: Double,
    val nodes: List<PlannedNodeDto>
)

@JsonClass(generateAdapter = true)
data class LatePickupDto(
    @Json(name = "pickup_request_id") val pickupRequestId: String,
    @Json(name = "late_sec") val lateSec: Int
)

/** Every requested pickup is in a route; the late ones also in [late], the rest in [unassigned]. */
@JsonClass(generateAdapter = true)
data class OptimisationJobResultDto(
    val id: String,
    val status: OptimizationJobStatusDto,
    val error: String? = null,
    val routes: List<PlannedRouteDto> = emptyList(),
    val late: List<LatePickupDto> = emptyList(),
    val unassigned: List<String> = emptyList()
)
